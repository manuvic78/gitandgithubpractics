#operadores aritméticos

print(3 + 2)  #suma
print(3 - 2)  #resta
print(3 * 2)  #multiplicación
print(3 / 2)  #división 
print(3 // 2) #división entera
print(3 % 2)  #módulo
print(3 ** 2) #potenciación

#estos se usan para hacer operaciones matemáticas básicas

#operadores de comparación

print(3 > 2)   #mayor que
print(3 < 2)   #menor que
print(3 == 2)  #igual que
print(3 != 2)  #diferente que
print(3 >= 2)  #mayor o igual que
print(3 <= 2)  #menor o igual que

#estos devuelven un valor booleano (True o False)

#operadores lógicos
print(True and False)  #AND
print(True or False)   #OR  
print(not True)        #NOT
#estos también devuelven un valor booleano (True o False)
#se usan para combinar expresiones booleanas
#AND devuelve True si ambas expresiones son True
#OR devuelve True si al menos una de las expresiones es True
#NOT invierte el valor de la expresión es decir que si es True devuelve False y viceversa
#ejemplos de uso de operadores lógicos
a = 5
b = 10
print(a > 3 and b < 15)  #True
print(a < 3 or b < 15)   #True
print(not(a > 3))        #False
#estos operadores son fundamentales en la toma de decisiones dentro de un programa